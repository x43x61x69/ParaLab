# Each column stores seven pixels. Unassigned characters share the blank glyph.
blank = (0,) * 5
glyphs = [blank]
indices = [0] * 96
for char, rows in G.items():
    code = ord(char)
    slot = code - 32 if code >= 32 else 92 + code  # \x01..\x03 -> 93..95
    columns = tuple(sum(1 << y for y, row in enumerate(rows) if row[x] == "#") for x in range(5))
    if columns not in glyphs:
        glyphs.append(columns)
    indices[slot] = glyphs.index(columns)

out = ['/* Generated by gen/font.py: indices and column bits for a 5x7 font. */',
       'static const unsigned char font_index[96]={']
for start in range(0, len(indices), 16):
    out.append('  ' + ','.join(f'0x{index:02x}' for index in indices[start:start + 16]) + ',')
out += ['};', 'static const unsigned char font_columns[][5]={']
for glyph in glyphs:
    out.append('  {' + ','.join(f'0x{column:02x}' for column in glyph) + '},')
out.append('};')
with open('font.h', 'w') as output:
    output.write('\n'.join(out) + '\n')
