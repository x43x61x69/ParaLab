# Each column stores seven pixels. Unassigned characters share the blank glyph.
blank = (0,) * 5
glyphs = [blank]
indices = [0] * 96
for char, rows in G.items():
    code = ord(char)
    slot = code - 32 if code >= 32 else 92 + code  # \x01..\x03 -> 93..95
    columns = tuple(sum(1 << y for y, row in enumerate(rows) if row[x] == "#") for x in range(5))
    if columns not in glyphs:
        glyphs.append(columns)
    indices[slot] = glyphs.index(columns)

out = ['/* Generated by gen/font.py: indices and column bits for a 5x7 font. */',
       'static const unsigned char font_index[96]={']
for start in range(0, len(indices), 16):
    out.append('  ' + ','.join(f'0x{index:02x}' for index in indices[start:start + 16]) + ',')
out += ['};', 'static const unsigned char font_columns[][5]={']
for glyph in glyphs:
    out.append('  {' + ','.join(f'0x{column:02x}' for column in glyph) + '},')
out.append('};')
destination = Path(__file__).resolve().parent.parent
(destination / 'font.h').write_text('\n'.join(out) + '\n')

source = destination.parents[2] / 'shared/title_font.h'
titles = re.findall(r'/\* ([A-Z]) \*/ \{([^}]*)\}', source.read_text())
assert ''.join(letter for letter, _ in titles) == 'ABCDEFGHIJKLMNOPQRSTUVWXYZ'
palette, offsets, runs = [], [], []
for _, values in titles:
    rows = [int(row, 16) for row in values.split(',')]
    assert len(rows) == 12
    offsets.append(len(runs))
    for row, repeated in groupby(rows):
        if row not in palette:
            palette.append(row)
        count = len(list(repeated))
        while count:
            size = min(count, 8)
            runs.append(((size - 1) << 5) | palette.index(row))
            count -= size
assert len(palette) <= 32 and len(runs) <= 256
out = ['/* Generated by gen/font.py. Each run packs its length minus one and a row index. */']
for name, values in [('title_rows', palette), ('title_offsets', offsets), ('title_runs', runs)]:
    out.append(f'static const unsigned char {name}[]={{')
    for start in range(0, len(values), 16):
        out.append('  ' + ','.join(f'0x{value:02x}' for value in values[start:start + 16]) + ',')
    out.append('};')
(destination / 'title_rows.h').write_text('\n'.join(out) + '\n')
